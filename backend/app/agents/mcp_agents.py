class MCPServer:
    """
    Model Context Protocol Server
    Coordinates Llama 4 and Qwen 3.5 agents with tool/resource management
    """
    
    def __init__(self):
        self.agents: Dict[str, Any] = {}
        self.resources: Dict[str, MCPResource] = {}
        self.tools: Dict[str, MCPTool] = {}
        self.sessions: Dict[str, List[MCPMessage]] = {}
        
    async def register_agent(self, name: str, agent: Any):
        """Register an agent with the MCP server"""
        await agent.initialize()
        self.agents[name] = agent
        print(f"Registered agent: {name}")
        
    async def register_tool(self, tool: MCPTool):
        """Register a tool available to all agents"""
        self.tools[tool.name] = tool
        
    async def register_resource(self, resource: MCPResource):
        """Register a resource (image, document, etc.)"""
        self.resources[resource.uri] = resource
        
    async def create_session(self, session_id: str) -> str:
        """Create a new conversation session"""
        self.sessions[session_id] = []
        return session_id
    
    async def send_message(
        self,
        session_id: str,
        message: MCPMessage,
        preferred_agent: Optional[str] = None
    ) -> Dict[str, Any]:
        """Send a message to the appropriate agent"""
        if session_id not in self.sessions:
            await self.create_session(session_id)
            
        # Add message to session history
        self.sessions[session_id].append(message)
        
        # Select agent based on message content and capabilities
        agent_name = preferred_agent or await self._select_agent(message)
        agent = self.agents.get(agent_name)
        
        if not agent:
            raise ValueError(f"Agent {agent_name} not found")
        
        # Process through selected agent
        if isinstance(agent, Llama4Agent):
            response = await agent.process_request(self.sessions[session_id])
        elif isinstance(agent, Qwen35Agent):
            if message.resources:
                # Multi-modal request
                for resource in message.resources:
                    if "image" in resource.mime_type:
                        response = await agent.analyze_image(resource.data)
                    elif "video" in resource.mime_type:
                        response = await agent.analyze_video(resource.data)
                    break
            else:
                response = await agent.process_request(self.sessions[session_id])
        else:
            raise ValueError(f"Unknown agent type: {type(agent)}")
        
        # Add assistant response to session
        self.sessions[session_id].append(
            MCPMessage(role="assistant", content=response.get("response", ""))
        )
        
        return response
    
    async def _select_agent(self, message: MCPMessage) -> str:
        """Select the best agent for the message"""
        # Check for multi-modal content
        if message.resources:
            return "qwen-3.5"
        
        # Check for crisis keywords → Llama 4 for safety handling
        crisis_keywords = ["suicide", "crisis", "emergency", "self-harm"]
        if any(keyword in message.content.lower() for keyword in crisis_keywords):
            return "llama-4"
        
        # Default to Llama 4 for text conversations
        return "llama-4"


# Factory function for creating MCP-enabled agent cluster
async def create_mcp_agent_cluster() -> MCPServer:
    """Create and initialize the MCP agent cluster"""
    server = MCPServer()
    
    # Initialize agents
    llama4 = Llama4Agent()
    qwen35 = Qwen35Agent()
    
    # Register agents
    await server.register_agent("llama-4", llama4)
    await server.register_agent("qwen-3.5", qwen35)
    
    # Register wellness-specific tools
    await server.register_tool(MCPTool(
        name="wellness_boundary_check",
        description="Validate response against wellness boundaries",
        input_schema={"type": "object", "properties": {"text": {"type": "string"}}},
        handler=lambda x: True
    ))
    
    await server.register_tool(MCPTool(
        name="crisis_escalation",
        description="Escalate to crisis resources",
        input_schema={"type": "object", "properties": {"language": {"type": "string"}}},
        handler=lambda x: {"escalated": True}
    ))
    
    return server
